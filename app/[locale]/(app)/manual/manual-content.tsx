function Section({ id, title, children }: { id: string; title: string; children: React.ReactNode }) {
  return (
    <section id={id} className="scroll-mt-6 mb-12">
      <h2 className="text-xl font-bold border-b pb-2 mb-4">{title}</h2>
      <div className="space-y-4 text-sm leading-relaxed text-foreground/90">{children}</div>
    </section>
  );
}

function H3({ children }: { children: React.ReactNode }) {
  return <h3 className="text-base font-semibold mt-6 mb-2 first:mt-0">{children}</h3>;
}

function P({ children }: { children: React.ReactNode }) {
  return <p>{children}</p>;
}

function UL({ items }: { items: React.ReactNode[] }) {
  return (
    <ul className="list-disc pl-5 space-y-1.5">
      {items.map((item, i) => (
        <li key={i}>{item}</li>
      ))}
    </ul>
  );
}

function StatusFlow({ steps }: { steps: string[] }) {
  return (
    <div className="flex flex-wrap items-center gap-1.5 rounded-lg border bg-muted/30 p-3">
      {steps.map((step, i) => (
        <div key={i} className="flex items-center gap-1.5">
          <span className="rounded-full bg-background border px-2.5 py-1 text-xs font-medium whitespace-nowrap">{step}</span>
          {i < steps.length - 1 && <span className="text-muted-foreground text-xs">→</span>}
        </div>
      ))}
    </div>
  );
}

function Callout({ variant = "info", children }: { variant?: "info" | "warning"; children: React.ReactNode }) {
  const Icon = variant === "warning" ? AlertTriangle : Info;
  return (
    <div
      className={cn(
        "flex gap-2 rounded-lg border p-3 text-xs leading-relaxed",
        variant === "warning"
          ? "border-destructive/30 bg-destructive/5 text-destructive"
          : "border-primary/20 bg-primary/5 text-foreground/90"
      )}
    >
      <Icon className="h-4 w-4 shrink-0 mt-0.5" />
      <div className="space-y-1">{children}</div>
    </div>
  );
}

function FieldTable({ rows }: { rows: { label: string; desc: React.ReactNode }[] }) {
  return (
    <div className="rounded-lg border overflow-hidden">
      <table className="w-full text-xs">
        <tbody>
          {rows.map((r, i) => (
            <tr key={i} className={i > 0 ? "border-t" : undefined}>
              <td className="w-36 shrink-0 bg-muted/40 px-3 py-2 font-medium align-top whitespace-nowrap">{r.label}</td>
              <td className="px-3 py-2 align-top">{r.desc}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

